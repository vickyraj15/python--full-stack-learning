name = "vicky"
print(len(name)) # getting the length of the string
print(name.endswith("y")) # checking if the string ends with "y"
print(name.startswith("v")) # checking if the string starts with "v" 
print(name.capitalize()) # capitalizing the first letter of the string
print(name.upper()) # converting the string to uppercase
print(name.title()) # converting the first letter of each word to uppercase
print(name.lower()) # converting the string to lowercase
print(name.count("i")) # counting the number of occurrences of "i" in the string
print(name.find("c")) # finding the index of the first occurrence of "c" in the string
print(name.replace("v", "b")) # replacing "v" with "b