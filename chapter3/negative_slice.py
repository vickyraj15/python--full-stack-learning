name = "vicky"

print(name[0:3]) # slicing the string to get the first three characters
print(name[-4:1]) # slicing the string using negative indices to get the first three characters
print(name[1:4]) # slicing the string to get characters from index 1 to 3
print(name[:4]) # is same as name[0:4], slicing the string to get the first four characters
print(name[1:]) # slicing the string to get characters from index 1 to the
print(name[1:4])
